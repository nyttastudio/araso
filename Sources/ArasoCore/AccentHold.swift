/// A normally composed letter whose repeat events can offer accent candidates.
/// Kept independent of AppKit so release/repeat ordering and case mapping can be tested.
public struct AccentHold {
    public let letter: Character
    public let keyCode: UInt16
    public private(set) var isVisible = false
    public private(set) var isDown = true
    public let candidates: [Character]
    public private(set) var selected = 0
    public var accent: Character { candidates[selected] }
    public var pageStart: Int { selected / 9 * 9 }
    public var page: Range<Int> { pageStart..<min(pageStart + 9, candidates.count) }

    public init?(letter: Character, keyCode: UInt16, profiles: [AccentProfile] = [.german]) {
        let candidates = AccentProfile.candidates(for: letter, profiles: profiles)
        guard !candidates.isEmpty else { return nil }
        self.letter = letter
        self.keyCode = keyCode
        self.candidates = candidates
    }

    public static func accent(for letter: Character) -> Character? {
        AccentProfile.candidates(for: letter, profiles: [.german]).first
    }

    public mutating func move(_ offset: Int) {
        selected = (selected + offset % candidates.count + candidates.count) % candidates.count
    }

    public mutating func movePage(_ direction: Int) {
        let pages = (candidates.count + 8) / 9
        let next = (pageStart / 9 + direction % pages + pages) % pages
        selected = next * 9
    }

    @discardableResult public mutating func select(_ index: Int) -> Bool {
        guard candidates.indices.contains(index) else { return false }
        selected = index
        return true
    }

    /// Auto-repeat is generated by a held key, never by waiting after a short tap.
    public mutating func repeatKey() {
        if isDown { isVisible = true }
    }

    /// True means the pending short-press tracking can be discarded. The letter is already composed.
    public mutating func release() -> Bool {
        guard isDown else { return false }
        isDown = false
        return !isVisible
    }
}
